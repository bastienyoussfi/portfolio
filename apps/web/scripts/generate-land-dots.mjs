/**
 * Generates the dot grid behind the places map.
 *
 * Walks a lat/lon grid, asks whether each cell falls on land, and writes the
 * result to src/data/land-dots.js as run-length encoded rows. This runs by hand
 * (`node scripts/generate-land-dots.mjs`), not on every build — the world does
 * not change often, and the output is committed.
 *
 * world-atlas, topojson-client and d3-geo are devDependencies used only here;
 * nothing map-related ends up in the shipped bundle.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { feature } from 'topojson-client'
import { geoContains } from 'd3-geo'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

// Grid step in degrees. Smaller = denser dots = larger output.
const STEP = 1.5

// Latitude crop. Cutting Antarctica and the empty far north gives the map a
// banner proportion and removes a large featureless blob from the bottom.
const LAT_MIN = -56
const LAT_MAX = 78
const LON_MIN = -180
const LON_MAX = 180

const topo = JSON.parse(readFileSync(resolve(root, 'node_modules/world-atlas/land-50m.json')))
const land = feature(topo, topo.objects.land)

const cols = Math.round((LON_MAX - LON_MIN) / STEP)
const rows = Math.round((LAT_MAX - LAT_MIN) / STEP)

// Each row becomes [start, length, start, length, ...] runs of land cells.
const encoded = []
let total = 0

for (let row = 0; row < rows; row++) {
  const lat = LAT_MAX - row * STEP
  const runs = []
  let start = -1

  for (let col = 0; col <= cols; col++) {
    const onLand = col < cols && geoContains(land, [LON_MIN + col * STEP, lat])
    if (onLand && start === -1) start = col
    if (!onLand && start !== -1) {
      runs.push(start, col - start)
      total += col - start
      start = -1
    }
  }

  encoded.push(runs)
}

const out = `/* GENERATED by scripts/generate-land-dots.mjs — do not edit by hand.
   ${total} land cells on a ${cols}x${rows} grid at ${STEP}° steps. */

export const GRID = {
  cols: ${cols},
  rows: ${rows},
  lonMin: ${LON_MIN},
  lonMax: ${LON_MAX},
  latMin: ${LAT_MIN},
  latMax: ${LAT_MAX},
}

/** Run-length encoded land cells, one entry per row: [start, length, ...]. */
export const LAND = ${JSON.stringify(encoded)}
`

mkdirSync(resolve(root, 'src/data'), { recursive: true })
writeFileSync(resolve(root, 'src/data/land-dots.js'), out)

console.log(`${total} land dots on a ${cols}x${rows} grid -> src/data/land-dots.js`)
